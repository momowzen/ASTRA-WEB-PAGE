export function getBoss(id: string): Boss | undefined {
  return BOSSES.find(b => b.id === id)
}

export function getBossName(boss: Boss, lang: Language = 'en'): string {
  if (lang === 'en') return boss.name
  return BOSSES_NAMES[lang][boss.id] ?? boss.name
}


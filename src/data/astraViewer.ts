function koParticle(n: string, t: 'subj' | 'obj' | 'top'): string {
  const last = n.charCodeAt(n.length - 1)
  const hasBatchim = (last - 0xac00) % 28 !== 0
  const p = {
    subj: ['이', '가'],
    obj: ['을', '를'],
    top: ['은', '는'],
  }
  return hasBatchim ? p[t][0] : p[t][1]
}
